public class Calculadora {
    /**
     * Este metodo é utilizado para somar dois numeros inteiros.
     * @param numeroUm este é o primeiro parametro do método
     * @param numeroDois este é o segundo parametro do método
     * @return int o resultado desde método é a soma dos dois numeros
     * @throws IllegalArgumentException Se a operação não for "S" ou "M"
     */
    public int somar(int numeroUm, int numeroDois) {
        return numeroUm + numeroDois;
    }
}
